def get_indicator_name(key: str) -> str:
    return INDICATOR_NAMES.get(key, key)


def get_indicator_rubric(key: str, score: int) -> str:
    """根据指标和分数返回对应的评分标准描述"""
    rubric = INDICATOR_RUBRIC.get(key, {})
    if score >= 85:
        return rubric.get("优秀(85-100)", "")
    elif score >= 75:
        return rubric.get("良好(75-84)", "")
    elif score >= 55:
        return rubric.get("合格(55-74)", "")
    else:
        return rubric.get("不合格(0-54)", "")